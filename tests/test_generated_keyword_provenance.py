from __future__ import annotations

import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from lsprepost_mcp.config import PROJECTS_DIR
from lsprepost_mcp.io import write_json
from lsprepost_mcp.project_store import write_model_project
from lsprepost_mcp.provenance import verify_generated_project
from lsprepost_mcp.schema import default_model_spec, parse_model_spec


class GeneratedKeywordProvenanceTests(unittest.TestCase):
    def test_generated_project_passes_provenance_check(self) -> None:
        project_name = "unit_generated_provenance"
        project_dir = PROJECTS_DIR / project_name
        if project_dir.exists():
            shutil.rmtree(project_dir)
        try:
            result = write_model_project(parse_model_spec(default_model_spec(project_name, "shell_plate")))
            verification = verify_generated_project(Path(result["project_dir"]))
            self.assertTrue(verification["ok"], verification)
            self.assertEqual(verification["classification"], "generated_by_lsprepost_mcp")
            self.assertTrue(verification["checks"]["signature"]["ok"])
            self.assertTrue(verification["checks"]["model_json"]["ok"])
            self.assertTrue(verification["checks"]["checks_json"]["ok"])
        finally:
            if project_dir.exists():
                shutil.rmtree(project_dir)

    def test_handwritten_keyword_without_project_metadata_fails(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            project_dir = Path(tmp)
            (project_dir / "model.k").write_text("*KEYWORD\n*END\n", encoding="utf-8")
            verification = verify_generated_project(project_dir)
            self.assertFalse(verification["ok"], verification)
            self.assertEqual(verification["classification"], "unverified_keyword")
            self.assertFalse(verification["checks"]["signature"]["ok"])
            self.assertFalse(verification["checks"]["model_json"]["ok"])
            self.assertFalse(verification["checks"]["checks_json"]["ok"])

    def test_imported_keyword_project_is_not_reported_as_generated(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            project_dir = Path(tmp)
            (project_dir / "model.k").write_text(
                "*KEYWORD\n$ Generated by lsprepost_mcp\n*END\n",
                encoding="utf-8",
            )
            write_json(
                project_dir / "model.json",
                {
                    "schema_version": "0.2.0",
                    "spec": {"project_name": "imported_probe", "model_type": "imported_keyword"},
                    "metadata": {"model_type": "imported_keyword"},
                },
            )
            write_json(project_dir / "checks.json", {"ok": True, "keyword_path": str(project_dir / "model.k")})

            verification = verify_generated_project(project_dir)
            self.assertFalse(verification["ok"], verification)
            self.assertEqual(verification["classification"], "imported_keyword_project")
            self.assertFalse(verification["checks"]["not_imported_keyword"]["ok"])

    def test_signed_but_handwritten_keyword_does_not_match_model_json(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            project_dir = Path(tmp)
            raw = default_model_spec("fake_signed_keyword", "shell_plate")
            (project_dir / "model.k").write_text(
                "*KEYWORD\n$ Generated by lsprepost_mcp\n$ AI wrote this deck by hand\n*END\n",
                encoding="utf-8",
            )
            write_json(
                project_dir / "model.json",
                {
                    "schema_version": "0.2.0",
                    "spec": raw,
                    "metadata": {"model_type": "shell_plate"},
                },
            )
            write_json(project_dir / "checks.json", {"ok": True, "keyword_path": str(project_dir / "model.k")})

            verification = verify_generated_project(project_dir)
            self.assertFalse(verification["ok"], verification)
            self.assertEqual(verification["classification"], "keyword_mismatch")
            self.assertFalse(verification["checks"]["keyword_matches_generator"]["ok"])

    def test_verify_generated_k_script_accepts_generated_project(self) -> None:
        project_name = "unit_verify_generated_k_script"
        project_dir = PROJECTS_DIR / project_name
        if project_dir.exists():
            shutil.rmtree(project_dir)
        try:
            result = write_model_project(parse_model_spec(default_model_spec(project_name, "shell_plate")))
            completed = subprocess.run(
                [
                    "powershell",
                    "-NoProfile",
                    "-ExecutionPolicy",
                    "Bypass",
                    "-File",
                    "scripts\\verify_generated_k.ps1",
                    "-ProjectDir",
                    result["project_dir"],
                ],
                cwd=Path(__file__).resolve().parents[1],
                capture_output=True,
                text=True,
            )
            self.assertEqual(completed.returncode, 0, completed.stdout + completed.stderr)
            self.assertIn('"classification": "generated_by_lsprepost_mcp"', completed.stdout)
        finally:
            if project_dir.exists():
                shutil.rmtree(project_dir)


if __name__ == "__main__":
    unittest.main()

def test_streaming_validator_accepts_small_real_deck(tmp_path) -> None:
    from lsprepost_mcp.quarter_two_tnt import (
        iter_quarter_two_tnt_keyword,
        keyword_sha256,
        validate_quarter_two_tnt_keyword_file,
    )

    spec = _small_renderer_spec()
    keyword_path = tmp_path / "model.k"
    with keyword_path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.writelines(iter_quarter_two_tnt_keyword(spec))

    checks = validate_quarter_two_tnt_keyword_file(
        keyword_path,
        spec,
        expected_sha256=keyword_sha256(spec),
    )

    assert checks["ok"] is True, checks
    assert checks["summary"]["node_count"] == 592
    assert checks["summary"]["ale_element_count"] == 126
    assert checks["summary"]["spg_element_count"] == 20
    assert checks["summary"]["detonation_count"] == 1


def test_streaming_validator_rejects_lower_charge_detonation(tmp_path) -> None:
    from lsprepost_mcp.quarter_two_tnt import (
        iter_quarter_two_tnt_keyword,
        validate_quarter_two_tnt_keyword_file,
    )

    spec = _small_renderer_spec()
    keyword_path = tmp_path / "model.k"
    text = "".join(iter_quarter_two_tnt_keyword(spec)).replace(
        "1,0,0.06,0,0\n",
        "4,0,0.06,0,0\n",
        1,
    )
    keyword_path.write_text(text, encoding="utf-8", newline="\n")

    checks = validate_quarter_two_tnt_keyword_file(keyword_path, spec)

    assert checks["ok"] is False
    assert any(item["id"] == "detonation.upper_only" and not item["ok"] for item in checks["items"])



def test_default_contract_has_exact_geometry_counts_and_mass() -> None:
    spec = validate_quarter_two_tnt_spec(default_quarter_two_tnt_spec())

    assert spec.project_name == "quarter_two_tnt_ale_spg"
    assert spec.model_type == "quarter_two_tnt_ale_spg"
    assert spec.unit_system == "SI_m_s_kg_N_Pa"
    assert spec.ale_cells == (100, 200, 100)
    assert spec.ale_node_count == 2_050_401
    assert spec.ale_element_count == 2_000_000
    assert spec.spg_cells == (10, 20, 10)
    assert spec.spg_node_count == 2_541
    assert spec.spg_element_count == 2_000
    assert spec.upper_ale_element_count == 2_000
    assert spec.lower_vacuum_element_count == 2_000
    assert spec.air_element_count == 1_996_000
    assert spec.quarter_tnt_mass_kg == pytest.approx(0.20864)
    assert spec.full_tnt_mass_kg == pytest.approx(0.83456)
    assert spec.detonation_point_m == (0.0, 0.06, 0.0)


@pytest.mark.parametrize(
    ("field", "value"),
    [
        ("mesh_size_m", 0.005),
        ("gap_m", 0.024),
        ("charge_edge_m", 0.084),
        ("end_time_s", 0.0003),
        ("d3plot_dt_s", 0.000004),
    ],
)
def test_fixed_approved_values_are_rejected_when_changed(field: str, value: float) -> None:
    raw = deepcopy(default_quarter_two_tnt_spec())
    raw[field] = value

    with pytest.raises(ValueError, match=field):
        validate_quarter_two_tnt_spec(raw)



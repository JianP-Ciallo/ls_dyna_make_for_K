def test_full_project_generation_transaction_and_provenance() -> None:
    import shutil
    from pathlib import Path

    from lsprepost_mcp.config import PROJECTS_DIR
    from lsprepost_mcp.project_store import validate_project_files
    from lsprepost_mcp.provenance import verify_generated_project
    from lsprepost_mcp.quarter_two_tnt import generate_quarter_two_tnt_project

    project_name = "pytest_quarter_two_tnt_transaction_v1"
    project_path = PROJECTS_DIR / project_name
    if project_path.exists():
        pytest.fail(f"reserved test project already exists: {project_path}")
    try:
        result = generate_quarter_two_tnt_project(
            {
                "project_name": project_name,
                "dry_run": False,
                "if_exists": "error",
            }
        )

        assert result["checks"]["ok"] is True, result["checks"]
        assert Path(result["keyword_path"]).is_file()
        assert Path(result["spec_path"]).is_file()
        assert Path(result["checks_path"]).is_file()
        refreshed = validate_project_files(project_path)
        assert refreshed["ok"] is True, refreshed
        verification = verify_generated_project(project_path)
        assert verification["ok"] is True, verification
        assert verification["classification"] == "generated_by_lsprepost_mcp"
    finally:
        if project_path.exists():
            shutil.rmtree(project_path)
def test_topology_ids_cover_exact_disjoint_ranges() -> None:
    from lsprepost_mcp.quarter_two_tnt import (
        ale_element_nodes,
        ale_node_id,
        spg_element_nodes,
        spg_node_id,
    )

    spec = validate_quarter_two_tnt_spec(default_quarter_two_tnt_spec())
    nx, ny, nz = spec.ale_cells
    sx, sy, sz = spec.spg_cells

    assert ale_node_id(spec, 0, 0, 0) == 1
    assert ale_node_id(spec, nx, ny, nz) == spec.ale_node_count
    assert ale_element_nodes(spec, 0, 0, 0) == (1, 2, nx + 3, nx + 2, (ny + 1) * (nx + 1) + 1, (ny + 1) * (nx + 1) + 2, (ny + 1) * (nx + 1) + nx + 3, (ny + 1) * (nx + 1) + nx + 2)
    assert spg_node_id(spec, 0, 0, 0) == spec.ale_node_count + 1
    assert spg_node_id(spec, sx, sy, sz) == spec.ale_node_count + spec.spg_node_count
    spg_nodes = spg_element_nodes(spec, 0, 0, 0)
    assert min(spg_nodes) > spec.ale_node_count
    assert max(spg_nodes) <= spec.ale_node_count + spec.spg_node_count


def test_boundary_iterators_have_exact_face_counts() -> None:
    from lsprepost_mcp.quarter_two_tnt import (
        iter_outer_boundary_segments,
        iter_x_symmetry_segments,
        iter_z_symmetry_segments,
    )

    spec = validate_quarter_two_tnt_spec(default_quarter_two_tnt_spec())
    nx, ny, nz = spec.ale_cells

    assert sum(1 for _ in iter_x_symmetry_segments(spec)) == ny * nz
    assert sum(1 for _ in iter_z_symmetry_segments(spec)) == nx * ny
    assert sum(1 for _ in iter_outer_boundary_segments(spec)) == ny * nz + 2 * nx * nz + nx * ny


def test_keyword_sha256_hashes_the_streamed_deck() -> None:
    import hashlib
    from dataclasses import replace

    from lsprepost_mcp.quarter_two_tnt import iter_quarter_two_tnt_keyword, keyword_sha256

    spec = validate_quarter_two_tnt_spec(default_quarter_two_tnt_spec())
    small = replace(
        spec,
        ale_cells=(1, 126, 1),
        spg_cells=(1, 20, 1),
        ale_node_count=508,
        ale_element_count=126,
        spg_node_count=84,
        spg_element_count=20,
        upper_ale_element_count=20,
        lower_vacuum_element_count=20,
        air_element_count=86,
    )
    expected = hashlib.sha256(
        "".join(iter_quarter_two_tnt_keyword(small)).encode("utf-8")
    ).hexdigest()

    assert keyword_sha256(small) == expected


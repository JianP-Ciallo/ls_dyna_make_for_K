from __future__ import annotations

import hashlib
from pathlib import Path

from .config import JSONDict
from .dyna_keyword import build_keyword
from .io import read_json
from .schema import parse_model_spec


GENERATOR_SIGNATURE = "$ Generated by lsprepost_mcp"
QUARTER_TWO_TNT_MODEL_TYPE = "quarter_two_tnt_ale_spg"
B120_SPG_SALE_MODEL_TYPE = "b120_spg_sale_rebuild"
STREAMED_MODEL_TYPES = {QUARTER_TWO_TNT_MODEL_TYPE, B120_SPG_SALE_MODEL_TYPE}


def verify_generated_project(project_dir: Path | str) -> JSONDict:
    path = Path(project_dir)
    keyword_path = path / "model.k"
    model_path = path / "model.json"
    checks_path = path / "checks.json"

    checks: JSONDict = {
        "project_dir": check_item(path.exists() and path.is_dir(), f"project directory exists: {path}"),
        "model_k": check_item(keyword_path.exists() and keyword_path.is_file(), f"model.k exists: {keyword_path}"),
        "model_json": check_item(model_path.exists() and model_path.is_file(), f"model.json exists: {model_path}"),
        "checks_json": check_item(checks_path.exists() and checks_path.is_file(), f"checks.json exists: {checks_path}"),
    }

    model_data: JSONDict = {}
    if checks["model_json"]["ok"]:
        try:
            data = read_json(model_path)
            if isinstance(data, dict):
                model_data = data
            checks["model_json_parse"] = check_item(isinstance(data, dict), "model.json is a JSON object")
        except Exception as exc:
            checks["model_json_parse"] = check_item(False, f"model.json parse failed: {exc}")
    else:
        checks["model_json_parse"] = check_item(False, "model.json is unavailable")

    checks_data: JSONDict = {}
    if checks["checks_json"]["ok"]:
        try:
            data = read_json(checks_path)
            if isinstance(data, dict):
                checks_data = data
            checks["checks_json_parse"] = check_item(isinstance(data, dict), "checks.json is a JSON object")
        except Exception as exc:
            checks["checks_json_parse"] = check_item(False, f"checks.json parse failed: {exc}")
    else:
        checks["checks_json_parse"] = check_item(False, "checks.json is unavailable")

    spec = model_data.get("spec", {}) if isinstance(model_data, dict) else {}
    model_type = str(spec.get("model_type", "")) if isinstance(spec, dict) else ""
    project_name = str(spec.get("project_name", "")) if isinstance(spec, dict) else ""

    keyword = ""
    if keyword_path.is_file() and model_type not in STREAMED_MODEL_TYPES:
        keyword = keyword_path.read_text(encoding="utf-8", errors="replace")
    signature_present = (
        file_contains_signature(keyword_path)
        if model_type in STREAMED_MODEL_TYPES
        else GENERATOR_SIGNATURE in keyword
    )
    checks["signature"] = check_item(
        signature_present,
        "model.k contains lsprepost_mcp generator signature",
        expected=GENERATOR_SIGNATURE,
    )
    checks["not_imported_keyword"] = check_item(
        model_type != "imported_keyword",
        "model.json spec.model_type is generated, not imported_keyword",
        actual=model_type or "missing",
    )
    checks["project_name"] = check_item(
        bool(project_name),
        "model.json contains spec.project_name",
        actual=project_name or "missing",
    )

    recorded_keyword = str(checks_data.get("keyword_path", "")) if isinstance(checks_data, dict) else ""
    checks["checks_keyword_path"] = check_item(
        (not recorded_keyword) or Path(recorded_keyword).name == "model.k",
        "checks.json keyword_path points to model.k when present",
        actual=recorded_keyword or "missing",
    )
    if model_type == B120_SPG_SALE_MODEL_TYPE:
        checks["keyword_matches_generator"] = generated_b120_keyword_match_check(keyword_path, spec)
    elif model_type == QUARTER_TWO_TNT_MODEL_TYPE:
        checks["keyword_matches_generator"] = generated_quarter_two_tnt_keyword_match_check(keyword_path, spec)
    else:
        checks["keyword_matches_generator"] = generated_keyword_match_check(keyword, spec, model_type)

    required = [
        "project_dir",
        "model_k",
        "model_json",
        "checks_json",
        "signature",
        "model_json_parse",
        "checks_json_parse",
        "not_imported_keyword",
        "project_name",
        "checks_keyword_path",
        "keyword_matches_generator",
    ]
    ok = all(bool(checks[name]["ok"]) for name in required)
    classification = "generated_by_lsprepost_mcp" if ok else classify_failure(checks, model_type)
    return {
        "ok": ok,
        "classification": classification,
        "project_dir": str(path),
        "keyword_path": str(keyword_path),
        "checks": checks,
    }


def file_contains_signature(path: Path, limit: int = 64 * 1024) -> bool:
    if not path.is_file():
        return False
    with path.open("rb") as handle:
        prefix = handle.read(limit)
    return GENERATOR_SIGNATURE.encode("utf-8") in prefix


def check_item(ok: bool, message: str, **detail: object) -> JSONDict:
    item: JSONDict = {"ok": bool(ok), "message": message}
    if detail:
        item["detail"] = detail
    return item


def classify_failure(checks: JSONDict, model_type: str) -> str:
    if model_type == "imported_keyword":
        return "imported_keyword_project"
    if checks.get("keyword_matches_generator", {}).get("ok") is False and checks.get("signature", {}).get("ok"):
        return "keyword_mismatch"
    if not checks.get("signature", {}).get("ok"):
        return "unverified_keyword"
    return "incomplete_generated_project"


def generated_b120_keyword_match_check(keyword_path: Path, spec: object) -> JSONDict:
    try:
        from .b120_spg_sale_rebuild import keyword_sha256, validate_spec
        expected_hash = keyword_sha256(validate_spec(spec))
        actual_hash = sha256_file(keyword_path)
    except Exception as exc:
        return check_item(False, f"could not stream-regenerate third-source model: {exc}")
    return check_item(actual_hash == expected_hash,
        "model.k exactly matches source-free third-model generation from model.json and pinned resources",
        actual_sha256=actual_hash, expected_sha256=expected_hash)


def generated_quarter_two_tnt_keyword_match_check(keyword_path: Path, spec: object) -> JSONDict:
    if not isinstance(spec, dict):
        return check_item(False, "model.json spec is unavailable or invalid")
    try:
        from .quarter_two_tnt import keyword_sha256, validate_quarter_two_tnt_spec

        normalized = validate_quarter_two_tnt_spec(spec)
        expected_hash = keyword_sha256(normalized)
        actual_hash = sha256_file(keyword_path)
    except Exception as exc:
        return check_item(False, f"could not stream-regenerate keyword from model.json spec: {exc}")
    return check_item(
        actual_hash == expected_hash,
        "model.k exactly matches the streamed keyword regenerated from model.json by lsprepost_mcp",
        actual_sha256=actual_hash,
        expected_sha256=expected_hash,
    )


def generated_keyword_match_check(keyword: str, spec: object, model_type: str) -> JSONDict:
    if model_type == "imported_keyword":
        return check_item(False, "imported keyword projects are not generated keyword decks")
    if not isinstance(spec, dict):
        return check_item(False, "model.json spec is unavailable or invalid")
    try:
        if model_type == "impact_1788_mmale_rebuild":
            from .impact_1788_rebuild import build_keyword as build_impact_keyword
            regenerated, _ = build_impact_keyword(spec)
        elif model_type == "gran_r5_mmale_rebuild":
            from .gran_r5_rebuild import build_keyword as build_gran_r5_keyword
            regenerated, _ = build_gran_r5_keyword(spec)
        else:
            regenerated, _ = build_keyword(parse_model_spec(spec))
    except Exception as exc:
        return check_item(False, f"could not regenerate keyword from model.json spec: {exc}")
    actual_hash = sha256_text(keyword)
    expected_hash = sha256_text(regenerated)
    return check_item(
        actual_hash == expected_hash,
        "model.k exactly matches keyword regenerated from model.json by lsprepost_mcp",
        actual_sha256=actual_hash,
        expected_sha256=expected_hash,
    )


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()
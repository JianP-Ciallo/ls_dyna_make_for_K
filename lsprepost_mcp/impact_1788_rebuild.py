"""Source-faithful 5-1788-2 compiler. Generation never reads the source mesh."""
from __future__ import annotations

import argparse
from copy import deepcopy
import json
from pathlib import Path

from .config import DEFAULT_UNIT_SYSTEM
from .impact_1788_mesh import DEFAULT_MESH, GEOMETRY, audit_mesh, build_mesh, estimate_mesh, validate_mesh_parameters
from .impact_1788_resources import SOURCE_SHA256, bundle_fingerprint, load_bundle, register_source, source_index
from .paths import safe_project_name

MODEL_TYPE = "impact_1788_mmale_rebuild"
SCHEMA_VERSION = "impact_1788.rebuild@1"
WARNINGS = [
    "Original MT=41 card is preserved; material implementation was not provided, so solver compatibility is unverified.",
    "Original absence of explicit axis SPC/nonreflecting boundaries is preserved; solver defaults require engineering review.",
    "No LS-DYNA solve or physical-response equivalence check has been performed.",
]


def default_spec(project_name: str = "impact_5_1788_2_rebuilt", *, radial_cells: list | None = None,
                 axial_cells: list | None = None) -> dict:
    return validate_spec({"schema_version":SCHEMA_VERSION,"model_type":MODEL_TYPE,"project_name":project_name,
        "unit_system":DEFAULT_UNIT_SYSTEM,"source_sha256":SOURCE_SHA256,"resource_bundle_sha256":bundle_fingerprint(),
        "geometry":deepcopy(GEOMETRY),"mesh":{"radial_cells":deepcopy(DEFAULT_MESH["radial_cells"] if radial_cells is None else radial_cells),
        "axial_cells":deepcopy(DEFAULT_MESH["axial_cells"] if axial_cells is None else axial_cells)}})


def validate_spec(raw: dict) -> dict:
    expected = {"schema_version":SCHEMA_VERSION,"model_type":MODEL_TYPE,"unit_system":DEFAULT_UNIT_SYSTEM,
                "source_sha256":SOURCE_SHA256,"resource_bundle_sha256":bundle_fingerprint(),"geometry":GEOMETRY}
    if not isinstance(raw,dict) or set(raw) != set(expected)|{"project_name","mesh"}:
        raise ValueError("second-source spec contains missing or unknown fields")
    for key,value in expected.items():
        if raw[key] != value:
            raise ValueError(f"{key} must preserve the approved source contract")
    if any(type(v) is bool for values in raw["geometry"].values() for v in values):
        raise ValueError("geometry coordinates must be numeric, not boolean")
    name=raw["project_name"]
    if not isinstance(name,str) or not name or safe_project_name(name) != name:
        raise ValueError("project_name must be a safe nonempty identifier")
    return {**deepcopy(raw),"mesh":validate_mesh_parameters(raw["mesh"])}


def _compile(raw: dict, *, check_mesh: bool) -> tuple[str,dict]:
    spec=validate_spec(raw)
    resources=load_bundle()
    mesh=build_mesh(spec["mesh"])
    quality=audit_mesh(mesh["nodes"],mesh["elements"],spec["mesh"]) if check_mesh else None
    if quality is not None and not quality["ok"]:
        raise ValueError(f"analytic mesh failed audit: {quality['errors']}")
    cards=sorted((c for r in resources for c in r["source_cards"]),key=lambda c:c["source_line_start"])
    chunks=[c["raw_text"].replace("\r\n","\n") for c in cards]
    # Keep the original KEYWORD options block exact. Generated comments belong
    # to the new NODE block and do not modify any nonmesh resource payload.
    chunks.append("*NODE\n$ Generated by lsprepost_mcp\n$ 5-1788-2 analytic grid; SI; original MT=41 implementation unavailable.\n")
    chunks.extend(f"{n[0]},{n[1]:.12g},{n[2]:.12g},{n[3]:.12g},0,0\n" for n in mesh["nodes"])
    chunks.append("*ELEMENT_SHELL\n")
    chunks.extend(",".join(map(str,e))+"\n" for e in mesh["elements"])
    chunks.append("*END\n")
    metadata={"model_type":MODEL_TYPE,"project_name":spec["project_name"],"unit_system":DEFAULT_UNIT_SYSTEM,
        "node_count":len(mesh["nodes"]),"element_count":len(mesh["elements"]),"element_family":"shell",
        "source_sha256":SOURCE_SHA256,"source_mesh_used_for_generation":False,
        "mesh_algorithm":"existing Phase15 rectangular topology, piecewise analytic axes and spatial part assignment",
        "geometry":deepcopy(GEOMETRY),"mesh_estimate":mesh["estimate"],"mesh_quality":quality,
        "components":[{"id":"pro / steel", "part_id":1,"material_id":1,"section_id":1,"eos_id":1,"hourglass_id":1},
                      {"id":"target / UMAT41", "part_id":2,"material_id":2,"section_id":1,"eos_id":0,"hourglass_id":1},
                      {"id":"air", "part_id":3,"material_id":3,"section_id":1,"eos_id":3,"hourglass_id":1}],
        "source_resources":[{"resource_id":r["id"],"original_ids":r["original_ids"],"dependencies":r["dependencies"],
            "source_cards":[{k:v for k,v in c.items() if k!="raw_text"} for c in r["source_cards"]]} for r in resources],
        "nonmesh_payload_policy":"exact source lines, including KEYWORD options; EOL normalization only",
        "mesh_bindings":{"part_ids":[1,2,3],"ale_group_part_ids":[1,2,3],"shared_material_interfaces":[[1,2],[1,3],[2,3]],
            "initial_velocity":{"part_id":1,"styp":2,"velocity_m_s":[0,-1788,0]},
            "source_explicit_sets_contacts_boundaries":[],"unmapped_source_mesh_references":[]},
        "semantic_warnings":list(WARNINGS),"validation_profile":MODEL_TYPE}
    return "".join(chunks),metadata


def build_keyword(spec: dict) -> tuple[str,dict]:
    return _compile(spec,check_mesh=True)


def validate_project(path: Path) -> dict:
    from .project_store import project_validation_fingerprint
    from .web.preview_mesh import parse_keyword_mesh
    errors,items=[],[]
    quality,spec={},{}
    def check(name,ok,message):
        items.append({"id":"impact_1788."+name,"ok":bool(ok),"severity":"info" if ok else "error","message":message})
        if not ok: errors.append(message)
    try:
        spec=validate_spec(json.loads((path/"model.json").read_text(encoding="utf-8"))["spec"])
        expected,_=_compile(spec,check_mesh=False)
        actual=(path/"model.k").read_text(encoding="utf-8")
        check("deterministic_rebuild",actual==expected,"Actual deck equals a fresh parameterized compile with pinned original physics")
        node_map,shells,solids=parse_keyword_mesh(actual)
        nodes=[[nid,*xyz] for nid,xyz in node_map.items()]
        elements=[[eid,pid,*conn] for pid,rows in shells.items() for eid,conn in rows]
        quality=audit_mesh(nodes,elements,spec["mesh"])
        check("mesh_quality",quality["ok"],"Actual geometry, spatial part membership, cell coverage, references and Jacobians pass")
        check("only_expected_elements",not solids,"Only the source four-node ALE2D element family is present")
        estimate=estimate_mesh(spec["mesh"])
        check("counts",len(nodes)==estimate["nodes"] and len(elements)==estimate["elements"],"Node and element counts match the recorded subdivision parameters")
        check("parts",{k:v["elements"] for k,v in quality["parts"].items()}==estimate["elements_by_part"],"Three original material regions are covered")
        check("interfaces",quality["interfaces"]==estimate["interfaces"],"All three shared material interfaces are preserved")
    except (OSError,ValueError,TypeError,KeyError,IndexError) as exc:
        check("read_compile",False,f"Reconstruction validation failed: {exc}")
    return {"ok":not errors,"errors":errors,"warnings":list(WARNINGS),"checks":items,
        "readiness":{"ok_for_gui_preview":not errors,"ok_for_solver_draft":False,"ok_for_production_review":False,
            "solver_blockers":["MT=41 implementation unavailable; original boundary defaults require engineering review"]},
        "validation_scope":{"ok_meaning":"static reconstruction fidelity only; no solver validation","profile_version":SCHEMA_VERSION},
        "counts":{"nodes":quality.get("node_count",0),"elements":quality.get("element_count",0),"parts":3},
        "mesh_quality":quality,"summary":{"project_name":spec.get("project_name",path.name),"model_type":MODEL_TYPE,"unit_system":DEFAULT_UNIT_SYSTEM},
        "keyword_path":str(path/"model.k"),"spec_path":str(path/"model.json"),
        "validation_fingerprint":project_validation_fingerprint(path)}


def generate_project(spec: dict, *, if_exists: str = "error") -> dict:
    from .project_store import write_compiled_keyword_project
    if if_exists not in {"error","versioned"}:
        raise ValueError("only error or versioned is supported; existing projects must be preserved")
    spec=validate_spec(spec)
    keyword,metadata=build_keyword(spec)
    return write_compiled_keyword_project(spec["project_name"],keyword,spec,metadata,if_exists=if_exists)


def input_schema() -> dict:
    return {"type":"object","properties":{
        "project_name":{"type":"string","default":"impact_5_1788_2_rebuilt"},
        "radial_cells":{"type":"array","minItems":2,"maxItems":2,"items":{"type":"integer","minimum":1,"maximum":1000}},
        "axial_cells":{"type":"array","minItems":3,"maxItems":3,"items":{"type":"integer","minimum":1,"maximum":1000}},
        "if_exists":{"type":"string","enum":["error","versioned"],"default":"error"}},"additionalProperties":False}


def _spec_from_args(args: dict) -> dict:
    if not isinstance(args,dict) or set(args)-set(input_schema()["properties"]):
        raise ValueError("unknown second-source tool input")
    if args.get("if_exists","error") not in {"error","versioned"}:
        raise ValueError("if_exists must be error or versioned")
    return default_spec(args.get("project_name","impact_5_1788_2_rebuilt"),
        **{k:args[k] for k in ("radial_cells","axial_cells") if k in args})


def tool_prepare(args: dict) -> dict:
    spec=_spec_from_args(args)
    return {"spec":spec,"mesh_estimate":estimate_mesh(spec["mesh"]),"resource_count":len(load_bundle()),
            "warnings":list(WARNINGS),"model_generated":False,"solver_launched":False}


def tool_generate(args: dict) -> dict:
    return generate_project(_spec_from_args(args),if_exists=args.get("if_exists","error"))


def main() -> None:
    parser=argparse.ArgumentParser(description=__doc__)
    sub=parser.add_subparsers(dest="command",required=True)
    sub.add_parser("register-resources").add_argument("source",type=Path)
    for name in ("prepare","generate"):
        entry=sub.add_parser(name)
        entry.add_argument("--project-name",default="impact_5_1788_2_rebuilt")
        entry.add_argument("--radial-cells",type=int,nargs=2)
        entry.add_argument("--axial-cells",type=int,nargs=3)
        entry.add_argument("--if-exists",choices=("error","versioned"),default="error")
        entry.add_argument("--spec-json",type=Path)
    args=vars(parser.parse_args())
    command=args.pop("command")
    if command=="register-resources": result=register_source(args["source"])
    else:
        path=args.pop("spec_json")
        spec=validate_spec(json.loads(path.read_text(encoding="utf-8"))) if path else _spec_from_args({k:v for k,v in args.items() if v is not None})
        if command=="prepare": result={"spec":spec,"mesh_estimate":estimate_mesh(spec["mesh"]),"resource_count":len(load_bundle()),"warnings":WARNINGS}
        else:
            result=generate_project(spec,if_exists=args["if_exists"])
            result={k:v for k,v in result.items() if k not in {"metadata","checks"}}|{"checks_ok":result["checks"]["ok"],"warnings":WARNINGS}
    print(json.dumps(result,ensure_ascii=False,indent=2))


if __name__=="__main__":
    main()

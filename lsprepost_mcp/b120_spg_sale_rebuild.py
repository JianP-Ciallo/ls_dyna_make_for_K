def default_spec(project_name='B120_C5_50_SPG_SALE_rebuilt', *, mesh=None):
    return validate_spec({'schema_version': SCHEMA_VERSION, 'model_type': MODEL_TYPE,
        'project_name': project_name, 'unit_system': DEFAULT_UNIT_SYSTEM, 'source_sha256': SOURCE_SHA256,
        'resource_bundle_sha256': bundle_fingerprint(), 'geometry': deepcopy(GEOMETRY),
        'mesh': deepcopy(DEFAULT_MESH if mesh is None else mesh)})


def validate_spec(raw):
    expected = {'schema_version': SCHEMA_VERSION, 'model_type': MODEL_TYPE, 'unit_system': DEFAULT_UNIT_SYSTEM,
                'source_sha256': SOURCE_SHA256, 'resource_bundle_sha256': bundle_fingerprint(), 'geometry': GEOMETRY}
    if not isinstance(raw, dict) or set(raw) != set(expected)|{'project_name', 'mesh'}:
        raise ValueError('third-source spec contains unknown or missing fields')
    for k, v in expected.items():
        if raw[k] != v: raise ValueError(f'{k} must preserve the approved source contract')
    def numeric(value):
        if isinstance(value, dict): return all(numeric(v) for v in value.values())
        if isinstance(value, list): return all(numeric(v) for v in value)
        return type(value) in (int, float) and math.isfinite(value)
    if not numeric(raw['geometry']): raise ValueError('geometry must contain finite numbers, not booleans')
    name = raw['project_name']
    if not isinstance(name, str) or not name or safe_project_name(name) != name:
        raise ValueError('project_name must be a safe nonempty name')
    return {**deepcopy(raw), 'mesh': validate_mesh_parameters(raw['mesh'])}


def _fields(*values, width=10):
    return ''.join(f'{str(v):>{width}}' for v in values)+'\n'


def _sale_cards():
    # DPID, bounds, number of cells and all non-ID options preserve the source.
    # Explicit reserved ranges avoid reliance on old node/element numbering.
    yield '*ALE_STRUCTURED_MESH\n'
    yield _fields(1001, 101, SALE_NODE_START, SALE_ELEMENT_START, '', '', '', '1.00000E16')
    yield _fields(1, 2, 3, 0, 0)
    for cpid, high, last in [(1, .5, 51), (2, .5, 51), (3, 1.6, 106)]:
        yield '*ALE_STRUCTURED_MESH_CONTROL_POINTS\n'
        yield _fields(cpid, '', '', '1.0', '', '0.0')
        yield _fields(1, '-0.5', '0.0', width=20)
        yield _fields(last, str(high), '0.0', width=20)


def _iter_prepared(spec, recipe, resources):
    cards = sorted((c for r in resources if r['reuse_policy'] == 'exact_original_card_payload'
                    for c in r['source_cards']), key=lambda c: c['source_line_start'])
    for card in cards: yield card['raw_text'].replace('\r\n', '\n')
    yield from _sale_cards()
    yield '*NODE\n$ Generated by lsprepost_mcp\n$ Analytic B120 blocks/extrusion; original mesh tables are not generation inputs.\n'
    for nid, x, y, z in recipe.iter_nodes():
        yield f'{nid:8d}{x:16.12g}{y:16.12g}{z:16.12g}{0:8d}{0:8d}\n'
    yield '*ELEMENT_SOLID\n'
    for row in recipe.iter_elements(): yield ''.join(f'{v:8d}' for v in row)+'\n'
    yield '*SET_NODE_LIST_TITLE\nguding\n'
    yield _fields(1, '0.0', '0.0', '0.0', '0.0', 'MECH')
    batch = []
    for nid in recipe.iter_bottom_nodes():
        batch.append(nid)
        if len(batch) == 8:
            yield _fields(*batch); batch = []
    if batch: yield _fields(*(batch+[0]*(8-len(batch))))
    yield '*SET_SEGMENT_TITLE\ntoushe\n'
    yield _fields(2, '0.0', '0.0', '0.0', '0.0', 'MECH')
    for face in recipe.iter_bottom_segments(): yield _fields(*face, '0.0', '0.0', '0.0', '0.0')
    yield '*END\n'


def iter_keyword(spec):
    spec = validate_spec(spec)
    yield from _iter_prepared(spec, build_recipe(spec['mesh']), load_bundle())


def keyword_sha256(spec):
    digest = hashlib.sha256()
    for text in iter_keyword(spec): digest.update(text.encode('utf-8'))
    return digest.hexdigest()



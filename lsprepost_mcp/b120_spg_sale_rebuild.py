def required_keywords(path, spec):
    validate_spec(spec)
    required = {c['keyword'] for r in source_index()['resources'] for c in r['source_cards']}
    required.update({'*KEYWORD', '*NODE', '*ELEMENT_SOLID', '*END'})
    with Path(path).open(encoding='utf-8') as f:
        present = {line.strip().split()[0].upper() for line in f if line.startswith('*')}
    items = {c: {'keyword': c, 'present': c in present} for c in sorted(required)}
    return {'ok': required <= present, 'items': items, 'missing': sorted(required-present)}


def _scan(path, estimate):
    node_count = element_count = fixed_count = face_count = 0
    by_part = Counter(); kw = ''; data_index = 0; issues = set(); digest = hashlib.sha256()
    maximum_node = NODE_START+estimate['nodes']-1
    with path.open('rb') as f:
        for raw in f:
            digest.update(raw); line = raw.decode('ascii').rstrip('\r\n')
            if line.startswith('*'):
                kw = line.strip().upper(); data_index = 0; continue
            if not line or line.startswith('$'): continue
            data_index += 1
            if kw == '*NODE':
                nid = int(line[:8]); values = [float(line[j:j+16]) for j in (8, 24, 40)]
                if nid != NODE_START+node_count or not all(math.isfinite(v) for v in values): issues.add('invalid node order or coordinate')
                if int(line[56:64]) != 0 or int(line[64:72]) != 0: issues.add('unexpected per-node constraints')
                node_count += 1
            elif kw == '*ELEMENT_SOLID':
                row = [int(line[j:j+8]) for j in range(0, 80, 8)]
                if row[0] != ELEMENT_START+element_count: issues.add('invalid element IDs')
                if min(row[2:]) < NODE_START or max(row[2:]) > maximum_node or len(set(row[2:])) != 8: issues.add('invalid element node references')
                by_part[row[1]] += 1; element_count += 1
            elif kw == '*SET_NODE_LIST_TITLE' and data_index > 2:
                ids = [int(line[j:j+10]) for j in range(0, len(line), 10) if line[j:j+10].strip()]
                fixed_count += sum(v > 0 for v in ids)
                if any(v and not NODE_START <= v <= maximum_node for v in ids): issues.add('invalid fixed-set node references')
            elif kw == '*SET_SEGMENT_TITLE' and data_index > 2:
                ids = [int(line[j:j+10]) for j in (0, 10, 20, 30)]; face_count += 1
                if any(not NODE_START <= v <= maximum_node for v in ids) or len(set(ids)) != 4: issues.add('invalid segment references')
    if node_count != estimate['nodes'] or element_count != estimate['elements']: issues.add('mesh counts differ')
    if dict(by_part) != {int(k): v for k, v in estimate['elements_by_part'].items()}: issues.add('part element counts differ')
    if fixed_count != estimate['bottom_nodes'] or face_count != estimate['bottom_segments']: issues.add('boundary counts differ')
    return {'ok': not issues, 'issues': sorted(issues), 'sha256': digest.hexdigest(),
            'nodes': node_count, 'elements': element_count, 'elements_by_part': dict(by_part),
            'fixed_nodes': fixed_count, 'bottom_segments': face_count}


def validate_project(path):
    from .project_store import project_validation_fingerprint
    path = Path(path); errors = []; checks = []; quality = {}; scan = {}
    def add(name, ok, message):
        checks.append({'id': 'b120.'+name, 'ok': bool(ok), 'severity': 'info' if ok else 'error', 'message': message})
        if not ok: errors.append(message)
    try:
        spec = validate_spec(json.loads((path/'model.json').read_text(encoding='utf-8'))['spec'])
        recipe = build_recipe(spec['mesh']); resources = load_bundle(); quality = recipe.quality
        scan = _scan(path/'model.k', recipe.estimate)
        add('actual_mesh_references', scan['ok'], 'Actual node/element IDs, connectivity ranges, part and boundary counts: '+str(scan['issues']))
        digest = hashlib.sha256()
        for line in _iter_prepared(spec, recipe, resources): digest.update(line.encode())
        add('deterministic_rebuild', scan['sha256'] == digest.hexdigest(), 'Actual deck matches fresh source-free parameterized generation with all pinned physics and bindings')
        cards = required_keywords(path/'model.k', spec)
        add('required_cards', cards['ok'], 'All original physical keyword types and rebuilt mesh/set types are present')
        add('positive_extrusion', quality['minimum_axial_spacing_m'] > 0, 'Mapped cross-section Gauss determinants and extrusion lengths are positive; full-file equality binds this audit to the actual deck')
        add('disjoint_sale_ranges', NODE_START+recipe.estimate['nodes'] <= SALE_NODE_START and ELEMENT_START+recipe.estimate['elements'] <= SALE_ELEMENT_START, 'Implicit S-ALE ID ranges do not overlap explicit structural mesh IDs')
    except (OSError, ValueError, KeyError, TypeError, IndexError, UnicodeError) as exc:
        add('read_compile', False, f'Third-source validation failed: {exc}')
    return {'ok': not errors, 'errors': errors, 'warnings': WARNINGS, 'checks': checks,
        'readiness': {'ok_for_gui_preview': not errors, 'ok_for_solver_draft': False, 'ok_for_production_review': False,
            'solver_blockers': ['MT41 implementations unavailable; original overlapping bottom boundaries need engineering review']},
        'validation_scope': {'profile_version': SCHEMA_VERSION, 'ok_meaning': 'Static reconstruction fidelity; no solver or response-equivalence validation'},
        'counts': {k: scan.get(k, 0) for k in ('nodes', 'elements', 'fixed_nodes', 'bottom_segments')},
        'actual_mesh_scan': scan, 'section_quality': quality, 'keyword_path': str(path/'model.k'),
        'validation_fingerprint': project_validation_fingerprint(path)}


def generate_project(spec, *, if_exists='error'):
    from .cfile import write_server_cfile
    from .io import write_json
    from .locks import ProjectLock
    from .paths import project_dir
    from .project_store import (commit_project_dir, next_versioned_project_dir, temp_project_dir,
        mark_runtime_artifact, remove_runtime_artifact, rebase_committed_checks)
    spec = validate_spec(spec)
    if if_exists not in ('error', 'versioned'): raise ValueError('only error/versioned is supported; existing projects cannot be overwritten')
    with ProjectLock(spec['project_name']):
        path = project_dir(spec['project_name'])
        if path.exists():
            if if_exists == 'error': raise FileExistsError(f'project already exists: {path}')
            path = next_versioned_project_dir(spec['project_name']); spec['project_name'] = path.name
        tmp = temp_project_dir(path)
        tmp.mkdir(parents=True, exist_ok=False); mark_runtime_artifact(tmp)
        recipe = build_recipe(spec['mesh']); resources = load_bundle(); digest = hashlib.sha256()
        with (tmp/'model.k').open('x', encoding='utf-8', newline='\n') as f:
            for line in _iter_prepared(spec, recipe, resources): f.write(line); digest.update(line.encode())
            f.flush(); os.fsync(f.fileno())
        metadata = _metadata(spec, recipe, digest.hexdigest())
        write_json(tmp/'model.json', {'schema_version': '0.2.0', 'spec': spec, 'metadata': metadata})
        write_server_cfile(tmp, 'open_model.cfile', 'open_keyword.cfile', {'keyword_path': 'model.k'}, if_exists='overwrite')
        checks = validate_project(tmp); write_json(tmp/'checks.json', checks)
        if not checks['ok']: raise ValueError(f'generated project failed static checks; evidence retained at {tmp}: {checks["errors"]}')
        commit_project_dir(tmp, path, if_exists); remove_runtime_artifact(path)
        checks = rebase_committed_checks(checks, project_name=path.name, project_path=path)
        write_json(path/'checks.json', checks)
        return {'project': path.name, 'project_dir': str(path), 'keyword_path': str(path/'model.k'),
            'spec_path': str(path/'model.json'), 'checks_path': str(path/'checks.json'), 'cfile_path': str(path/'open_model.cfile'),
            'metadata': metadata, 'checks': checks, 'solver_started': False, 'if_exists': if_exists}


def input_schema():
    mesh_properties = {k: {'type': 'number' if k == 'axial_step_m' else 'integer'} for k in DEFAULT_MESH}
    return {'type': 'object', 'properties': {'project_name': {'type': 'string'},
        'mesh': {'type': 'object', 'properties': mesh_properties, 'required': list(DEFAULT_MESH), 'additionalProperties': False},
        'if_exists': {'type': 'string', 'enum': ['error', 'versioned']}}, 'additionalProperties': False}


def _tool_spec(args):
    if not isinstance(args, dict) or set(args)-{'project_name', 'mesh', 'if_exists'}:
        raise ValueError('unknown third-model input fields')
    if args.get('if_exists', 'error') not in ('error', 'versioned'): raise ValueError('unsupported if_exists')
    return default_spec(args.get('project_name', 'B120_C5_50_SPG_SALE_rebuilt'), mesh=args.get('mesh'))


def tool_prepare(args):
    spec = _tool_spec(args); resources = load_bundle()
    return {'spec': spec, 'mesh_estimate': estimate_mesh(spec['mesh']), 'resource_count': len(resources),
            'warnings': WARNINGS, 'model_generated': False, 'solver_started': False}


def tool_generate(args):
    return generate_project(_tool_spec(args), if_exists=args.get('if_exists', 'error'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['prepare', 'generate', 'register-resources'])
    parser.add_argument('source', nargs='?'); parser.add_argument('--project-name', default='B120_C5_50_SPG_SALE_rebuilt')
    parser.add_argument('--spec-json'); parser.add_argument('--if-exists', choices=['error', 'versioned'], default='error')
    args = parser.parse_args()
    if args.action == 'register-resources':
        if not args.source: parser.error('source path required')
        result = register_source(args.source)
    else:
        spec = json.loads(Path(args.spec_json).read_text(encoding='utf-8-sig')) if args.spec_json else default_spec(args.project_name)
        if args.action == 'generate': result = generate_project(spec, if_exists=args.if_exists)
        else:
            spec = validate_spec(spec); load_bundle()
            result = {'spec': spec, 'mesh_estimate': estimate_mesh(spec['mesh']), 'model_generated': False, 'solver_started': False}
    print(json.dumps(result, ensure_ascii=True, indent=2))


if __name__ == '__main__': main()

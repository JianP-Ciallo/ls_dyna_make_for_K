"""Controlled GRAN_R5 reconstruction compiler and project entry points.

Only the nonmesh resource registration command reads the source file. Generation
uses analytic geometry, scalar subdivisions, and registered physical resources.
No external application or solver is launched by this module.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
import hashlib
import json
from pathlib import Path

from .config import DEFAULT_UNIT_SYSTEM
from .gran_r5_mesh import GEOMETRY, audit_mesh, build_mesh, estimate_mesh, validate_mesh_parameters
from .paths import safe_project_name
from .source_rebuild_resources import SOURCE_SHA256, bundle_fingerprint, load_bundle, register_source, source_index

MODEL_TYPE = "gran_r5_mmale_rebuild"
SCHEMA_VERSION = "gran_r5.rebuild@1"
WARNINGS = [
    "MT=41 user material card is preserved, but its implementation is unavailable; solver compatibility is unverified.",
    "The source has no explicit axis SPC or nonreflecting boundary; no new boundary physics was added.",
    "Source opposite winding in 1600 explosive elements is replaced by consistently positive generated Jacobians.",
    "No LS-DYNA solve, calibration, or physical-response equivalence check has been performed.",
]


def _expected_bundle_fingerprint() -> str:
    cards = sorted((c["source_line_start"], c["raw_sha256"]) for r in source_index()["resources"] for c in r["source_cards"])
    return hashlib.sha256(json.dumps(cards, separators=(",", ":")).encode()).hexdigest()


def default_spec(project_name: str = "GRAN_R5_2D_MMALE_6MM_rebuilt", *, core_divisions: int = 20,
                 charge_layers: int = 20, concrete_layers: int = 30) -> dict:
    return validate_spec({"schema_version": SCHEMA_VERSION, "model_type": MODEL_TYPE,
        "project_name": project_name, "unit_system": DEFAULT_UNIT_SYSTEM,
        "source_sha256": SOURCE_SHA256, "resource_bundle_sha256": _expected_bundle_fingerprint(),
        "geometry": deepcopy(GEOMETRY),
        "mesh": {"core_divisions": core_divisions, "charge_layers": charge_layers, "concrete_layers": concrete_layers}})


def validate_spec(raw: dict) -> dict:
    keys = {"schema_version", "model_type", "project_name", "unit_system", "source_sha256",
            "resource_bundle_sha256", "geometry", "mesh"}
    if not isinstance(raw, dict) or set(raw) != keys:
        raise ValueError("GRAN_R5 spec has unknown or missing fields")
    for key, value in {"schema_version": SCHEMA_VERSION, "model_type": MODEL_TYPE,
                       "unit_system": DEFAULT_UNIT_SYSTEM, "source_sha256": SOURCE_SHA256,
                       "resource_bundle_sha256": _expected_bundle_fingerprint(), "geometry": GEOMETRY}.items():
        if raw[key] != value:
            raise ValueError(f"{key} must preserve the approved source reconstruction contract")
    name = raw["project_name"]
    if not isinstance(name, str) or not name or safe_project_name(name) != name:
        raise ValueError("project_name must be a safe nonempty project identifier")
    return {**deepcopy(raw), "mesh": validate_mesh_parameters(raw["mesh"])}


def _compile(raw: dict, *, check_mesh: bool) -> tuple[str, dict]:
    spec = validate_spec(raw)
    records = load_bundle()
    if bundle_fingerprint(records) != spec["resource_bundle_sha256"]:
        raise ValueError("resource bundle changed since the model spec was recorded")
    mesh = build_mesh(spec["mesh"])
    quality = audit_mesh(mesh["nodes"], mesh["elements"]) if check_mesh else None
    if quality is not None and not quality["ok"]:
        raise ValueError(f"analytic mesh failed validation: {quality['errors']}")
    cards = sorted((card for r in records for card in r["source_cards"]), key=lambda card: card["source_line_start"])
    chunks = ["*KEYWORD\n", "$ Generated by lsprepost_mcp\n",
        "$ GRAN_R5 analytic multiblock reconstruction; SI m-s-kg-N-Pa\n",
        "$ Physical definition lines preserved from reviewed nonmesh resources.\n",
        "$ MT=41 implementation unavailable; solver compatibility is unverified.\n"]
    chunks.extend(c["raw_text"].replace("\r\n", "\n") for c in cards)
    chunks.append("*NODE\n")
    chunks.extend(f"{int(n[0])},{n[1]:.12g},{n[2]:.12g},{n[3]:.12g},0,0\n" for n in mesh["nodes"])
    chunks.append("*ELEMENT_SHELL\n")
    chunks.extend(",".join(str(v) for v in e)+"\n" for e in mesh["elements"])
    chunks.append("*END\n")
    metadata = {"model_type": MODEL_TYPE, "project_name": spec["project_name"],
        "unit_system": DEFAULT_UNIT_SYSTEM, "node_count": len(mesh["nodes"]),
        "element_count": len(mesh["elements"]), "element_family": "shell",
        "source_sha256": SOURCE_SHA256, "source_mesh_used_for_generation": False,
        "mesh_algorithm": "phase15 rectangular topology + analytic half-square/semicircle maps",
        "geometry": deepcopy(GEOMETRY), "mesh_estimate": mesh["estimate"], "mesh_quality": quality,
        "components": [{"id":"COMP B", "part_id":1, "material_id":1, "section_id":1, "eos_id":1},
                       {"id":"CONCRETE / UMAT41", "part_id":2, "material_id":2, "section_id":1, "eos_id":0}],
        "source_resources": [{"resource_id": r["id"], "original_ids": r["original_ids"],
            "dependencies": r["dependencies"], "source_cards": [{k:v for k,v in c.items() if k!="raw_text"} for c in r["source_cards"]]} for r in records],
        "nonmesh_payload_policy": "exact original lines; line endings normalized by the project writer",
        "mesh_bindings": {"part_ids":[1,2],"shared_material_interface":True,
            "ale_group_part_ids":[1,2],"detonation_part_id":1,"detonation_xyz_m":[0,0,0],
            "source_explicit_sets_contacts_boundaries_loads":[],"unmapped_source_mesh_references":[]},
        "semantic_warnings": list(WARNINGS), "validation_profile": MODEL_TYPE}
    return "".join(chunks), metadata


def build_keyword(spec: dict) -> tuple[str, dict]:
    return _compile(spec, check_mesh=True)


def validate_project(path: Path) -> dict:
    from .project_store import project_validation_fingerprint
    from .web.preview_mesh import parse_keyword_mesh

    errors, items = [], []
    quality = {}
    spec = {}
    def check(name, ok, message):
        items.append({"id":"gran_r5."+name,"ok":bool(ok),"severity":"info" if ok else "error","message":message})
        if not ok: errors.append(message)
    try:
        model = json.loads((path/"model.json").read_text(encoding="utf-8"))
        spec = validate_spec(model["spec"])
        expected, _ = _compile(spec, check_mesh=False)
        actual = (path/"model.k").read_text(encoding="utf-8")
        check("deterministic_rebuild", actual==expected, "Actual deck equals fresh analytic compile with pinned physical resources")
        node_map, shells, solids = parse_keyword_mesh(actual)
        nodes = [[nid,*xyz] for nid,xyz in node_map.items()]
        elements = [[eid,pid,*nids] for pid,rows in shells.items() for eid,nids in rows]
        quality = audit_mesh(nodes,elements)
        check("mesh_quality", quality["ok"], "Actual mesh passes geometry, topology, references and Jacobian checks")
        check("only_expected_elements", not solids, "Only the source's four-node ALE2D element family is emitted")
        estimated = estimate_mesh(spec["mesh"])
        check("counts", len(nodes)==estimated["nodes"] and len(elements)==estimated["elements"], "Actual mesh counts match the parameterized block topology")
        if quality.get("parts"):
            check("parts", {k:v["elements"] for k,v in quality["parts"].items()}==estimated["elements_by_part"], "Part membership matches the reconstructed material regions")
        check("interface", quality.get("interface_edges")==estimated["interface_edges"], "Source material interface is conforming and shared")
    except (OSError, ValueError, TypeError, KeyError, IndexError) as exc:
        check("read_compile", False, f"Reconstruction validation failed: {exc}")
    return {"ok":not errors,"errors":errors,"warnings":list(WARNINGS),"checks":items,
        "readiness":{"ok_for_gui_preview":not errors,"ok_for_solver_draft":False,"ok_for_production_review":False,
            "solver_blockers":["MT=41 material implementation unavailable; original boundary physics requires review"]},
        "validation_scope":{"ok_meaning":"static geometry, source-fidelity and deterministic generation checks only; no solver validation"},
        "counts":{"nodes":quality.get("node_count",0),"elements":quality.get("element_count",0),"parts":2},
        "mesh_quality":quality,"summary":{"project_name":spec.get("project_name",path.name),"model_type":MODEL_TYPE,"unit_system":DEFAULT_UNIT_SYSTEM},
        "keyword_path":str(path/"model.k"),"spec_path":str(path/"model.json"),
        "validation_fingerprint":project_validation_fingerprint(path)}


def generate_project(spec: dict, *, if_exists: str = "error") -> dict:
    from .project_store import write_compiled_keyword_project
    if if_exists not in {"error","versioned"}:
        raise ValueError("GRAN_R5 generation supports only error or versioned; existing projects are preserved")
    normalized=validate_spec(spec)
    keyword,metadata=build_keyword(normalized)
    return write_compiled_keyword_project(normalized["project_name"],keyword,normalized,metadata,if_exists=if_exists)


def input_schema() -> dict:
    return {"type":"object","properties":{
        "project_name":{"type":"string","default":"GRAN_R5_2D_MMALE_6MM_rebuilt"},
        "core_divisions":{"type":"integer","minimum":2,"maximum":80,"multipleOf":2,"default":20},
        "charge_layers":{"type":"integer","minimum":1,"maximum":80,"default":20},
        "concrete_layers":{"type":"integer","minimum":1,"maximum":80,"default":30},
        "if_exists":{"type":"string","enum":["error","versioned"],"default":"error"}},"additionalProperties":False}


def _spec_from_args(args: dict) -> dict:
    if not isinstance(args,dict) or set(args)-set(input_schema()["properties"]):
        raise ValueError("unknown GRAN_R5 tool input")
    if args.get("if_exists","error") not in {"error","versioned"}:
        raise ValueError("if_exists must be error or versioned")
    return default_spec(args.get("project_name","GRAN_R5_2D_MMALE_6MM_rebuilt"),
        **{k:args[k] for k in ("core_divisions","charge_layers","concrete_layers") if k in args})


def tool_prepare(args: dict) -> dict:
    spec=_spec_from_args(args)
    resources=load_bundle()
    return {"spec":spec,"mesh_estimate":estimate_mesh(spec["mesh"]),"resource_count":len(resources),
            "warnings":list(WARNINGS),"model_generated":False,"solver_launched":False}


def tool_generate(args: dict) -> dict:
    return generate_project(_spec_from_args(args),if_exists=args.get("if_exists","error"))


def main() -> None:
    parser=argparse.ArgumentParser(description=__doc__)
    sub=parser.add_subparsers(dest="command",required=True)
    register=sub.add_parser("register-resources")
    register.add_argument("source",type=Path)
    for command in ("prepare","generate"):
        entry=sub.add_parser(command)
        entry.add_argument("--project-name",default="GRAN_R5_2D_MMALE_6MM_rebuilt")
        entry.add_argument("--core-divisions",type=int,default=20)
        entry.add_argument("--charge-layers",type=int,default=20)
        entry.add_argument("--concrete-layers",type=int,default=30)
        entry.add_argument("--if-exists",choices=("error","versioned"),default="error")
        entry.add_argument("--spec-json",type=Path)
    args=vars(parser.parse_args())
    command=args.pop("command")
    if command=="register-resources":
        result=register_source(args["source"])
    else:
        spec_path=args.pop("spec_json")
        spec=validate_spec(json.loads(spec_path.read_text(encoding="utf-8"))) if spec_path else _spec_from_args(args)
        if command=="prepare":
            result={"spec":spec,"mesh_estimate":estimate_mesh(spec["mesh"]),"resource_count":len(load_bundle()),"warnings":WARNINGS}
        else:
            result=generate_project(spec,if_exists=args["if_exists"])
            result={k:v for k,v in result.items() if k not in {"metadata","checks"}} | {"checks_ok":result["checks"]["ok"],"warnings":WARNINGS}
    print(json.dumps(result,ensure_ascii=False,indent=2))


if __name__=="__main__":
    main()

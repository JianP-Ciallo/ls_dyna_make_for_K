COMPILER = "lsprepost.r12_shell_plate@1"


@dataclass(frozen=True)
class PlateSpec:
    project_name: str = "plate_demo"
    length_mm: float = 100.0
    width_mm: float = 50.0
    thickness_mm: float = 2.0
    mesh_size_mm: float = 10.0
    material_name: str = "mild_steel"
    density_g_per_mm3: float = 0.00785
    youngs_mpa: float = 210000.0
    poisson: float = 0.3


def make_plate_spec_from_model_spec(model_spec: JSONDict) -> PlateSpec:
    model_type = str(model_spec.get("model_type", "shell_plate"))
    if model_type != "shell_plate":
        raise ValueError("only model_type='shell_plate' is supported in this first version")

    unit_system = str(model_spec.get("unit_system", "mm_ms_g_N_MPa"))
    if unit_system != "mm_ms_g_N_MPa":
        raise ValueError("only unit_system='mm_ms_g_N_MPa' is supported in this first version")

    geometry = model_spec.get("geometry") or {}
    mesh = model_spec.get("mesh") or {}
    material = model_spec.get("material") or {}
    boundary_conditions = model_spec.get("boundary_conditions", [])

    if not isinstance(geometry, dict):
        raise ValueError("spec.geometry must be an object")
    if not isinstance(mesh, dict):
        raise ValueError("spec.mesh must be an object")
    if not isinstance(material, dict):
        raise ValueError("spec.material must be an object")
    if not isinstance(boundary_conditions, list):
        raise ValueError("spec.boundary_conditions must be a list")

    fixed_edges = [
        item.get("edge")
        for item in boundary_conditions
        if isinstance(item, dict) and item.get("type") == "fixed_edge"
    ]
    if "x_min" not in fixed_edges:
        raise ValueError("this first version requires boundary_conditions to include fixed_edge x_min")

    spec = PlateSpec(
        project_name=str(model_spec.get("project_name", PlateSpec.project_name)),
        length_mm=float(geometry.get("length_mm", PlateSpec.length_mm)),
        width_mm=float(geometry.get("width_mm", PlateSpec.width_mm)),
        thickness_mm=float(geometry.get("thickness_mm", PlateSpec.thickness_mm)),
        mesh_size_mm=float(mesh.get("size_mm", PlateSpec.mesh_size_mm)),
        material_name=str(material.get("name", PlateSpec.material_name)),
        density_g_per_mm3=float(
            material.get("density_g_per_mm3", PlateSpec.density_g_per_mm3)
        ),
        youngs_mpa=float(material.get("youngs_mpa", PlateSpec.youngs_mpa)),
        poisson=float(material.get("poisson", PlateSpec.poisson)),
    )
    validate_spec(spec)
    return spec


def validate_spec(spec: PlateSpec) -> None:
    positive = {
        "length_mm": spec.length_mm,
        "width_mm": spec.width_mm,
        "thickness_mm": spec.thickness_mm,
        "mesh_size_mm": spec.mesh_size_mm,
        "density_g_per_mm3": spec.density_g_per_mm3,
        "youngs_mpa": spec.youngs_mpa,
    }
    for key, value in positive.items():
        if value <= 0:
            raise ValueError(f"{key} must be positive")
    if not 0.0 < spec.poisson < 0.5:
        raise ValueError("poisson must be between 0 and 0.5")


def build_plate_keyword(spec: PlateSpec, *, mesh: CheckedMesh,
                        grid: JSONDict | None = None) -> tuple[str, JSONDict]:
    nodes, elements = mesh.nodes, mesh.elements
    left_nodes = mesh.regions["plate.left_edge"]
    right_nodes = mesh.regions["plate.right_edge"]
    part_id, elform = mesh.part_id, shell_elform(mesh)
    thickness = r12_number(spec.thickness_mm, 10)
    material_row = "1," + ",".join(
        r12_number(value, 10) for value in (spec.density_g_per_mm3, spec.youngs_mpa, spec.poisson)
    )

    lines: list[str] = [
        "*KEYWORD",
        "*TITLE",
        f"R12 shell plate: {spec.project_name}",
        "$",
        "$ Unit system: mm_ms_g_N_MPa (mm, ms, g, N, MPa)",
        "$ Generated by lsprepost_mcp/r12_plate.py",
        "$",
        "*CONTROL_TERMINATION",
        "$#  endtim    endcyc     dtmin    endeng    endmas",
        "1.000000,0,0.0,0.0,0.0",
    ]
    if sort_card := shell_sort_card(mesh):
        lines.extend(["*CONTROL_SHELL", sort_card])
    lines.extend([
        "*DATABASE_BINARY_D3PLOT",
        "$#      dt",
        "0.100000",
        "*NODE",
        "$#   nid               x               y               z",
    ])
    for nid, x, y, z in nodes:
        coordinates = ",".join(r12_number(value, 16) for value in (x, y, z))
        lines.append(f"{nid},{coordinates}")

    lines.extend(
        [
            "*ELEMENT_SHELL",
            "$#   eid     pid      n1      n2      n3      n4",
        ]
    )
    for element in elements:
        lines.append(",".join(str(value) for value in element))

    lines.extend(
        [
            "*PART",
            "steel_shell_plate",
            "$#   pid     secid       mid     eosid      hgid      grav    adpopt      tmid",
            f"{part_id},1,1,0,0,0,0,0",
            "*SECTION_SHELL",
            "$# secid    elform      shrf       nip     propt   qr/irid     icomp     setyp",
            f"1,{elform},0.833000,5,1.0,0,0,0",
            "$#     t1        t2        t3        t4      nloc     marea",
            ",".join([thickness] * 4 + ["0.0", "0.0"]),
            "*MAT_ELASTIC",
            "$#   mid        ro         e        pr",
            material_row,
            "*SET_NODE_LIST",
            "$#   sid       da1       da2       da3       da4",
            "1001,0,0,0,0",
            "$ left edge nodes",
        ]
    )
    lines.extend(format_id_lines(left_nodes))
    lines.extend(
        [
            "*SET_NODE_LIST",
            "$#   sid       da1       da2       da3       da4",
            "1002,0,0,0,0",
            "$ right edge nodes",
        ]
    )
    lines.extend(format_id_lines(right_nodes))
    lines.extend(
        [
            "*BOUNDARY_SPC_SET",
            "$#  nsid       cid      dofx      dofy      dofz     dofrx     dofry     dofrz",
            "1001,0,1,1,1,1,1,1",
            "*END",
        ]
    )

    metadata = {
        "unit_system": "mm_ms_g_N_MPa",
        "node_count": len(nodes),
        "element_count": len(elements),
        "part_count": 1,
        "material_count": 1,
        "section_count": 1,
        "left_edge_node_set": 1001,
        "right_edge_node_set": 1002,
        "mesh": grid or {},
    }
    return "\n".join(lines) + "\n", metadata


def format_id_lines(ids: list[int]) -> list[str]:
    rows = []
    for start in range(0, len(ids), 8):
        rows.append(",".join(str(value) for value in ids[start : start + 8]))
    return rows


def validate_project_files(path: Path, *, mesh: CheckedMesh | None = None) -> JSONDict:
    keyword_path = path / "model.k"
    spec_path = path / "model.json"
    errors: list[str] = []
    warnings: list[str] = []

    if not keyword_path.exists():
        errors.append("model.k is missing")
        keyword = ""
    else:
        keyword = keyword_path.read_text(encoding="utf-8")

    if not spec_path.exists():
        errors.append("model.json is missing")
        spec = {}
    else:
        spec = read_json(spec_path)

    required_cards = [
        "*KEYWORD",
        "*NODE",
        "*ELEMENT_SHELL",
        "*PART",
        "*SECTION_SHELL",
        "*MAT_ELASTIC",
        "*SET_NODE_LIST",
        "*BOUNDARY_SPC_SET",
        "*END",
    ]
    for card in required_cards:
        if card not in keyword:
            errors.append(f"{card} card is missing")

    if "mm_ms_g_N_MPa" not in keyword:
        errors.append("unit system marker mm_ms_g_N_MPa is missing")

    metadata = spec.get("metadata", {}) if isinstance(spec, dict) else {}
    if metadata.get("node_count", 0) <= 0:
        errors.append("node_count must be positive")
    if metadata.get("element_count", 0) <= 0:
        errors.append("element_count must be positive")
    if metadata.get("material_count") != 1:
        errors.append("expected exactly one material")
    if metadata.get("section_count") != 1:
        errors.append("expected exactly one shell section")

    user_spec = spec.get("spec", {}) if isinstance(spec, dict) else {}
    physical = extract_physical_values(user_spec)
    if physical.get("thickness_mm", 0) <= 0:
        errors.append("thickness_mm must be positive")
    if physical.get("density_g_per_mm3", 0) <= 0:
        errors.append("density_g_per_mm3 must be positive")
    if physical.get("youngs_mpa", 0) <= 0:
        errors.append("youngs_mpa must be positive")

    if physical.get("mesh_size_mm", 0) > min(
        physical.get("length_mm", 0), physical.get("width_mm", 0)
    ):
        warnings.append("mesh_size_mm is larger than one plate dimension; mesh is very coarse")

    binding_check = {}
    mesh_id = metadata.get("mesh_id")
    if not mesh_id:
        errors.append("mesh_id is missing")
    else:
        try:
            plate = make_plate_spec_from_model_spec(user_spec)
            if mesh is None:
                mesh, _ = load_for_configuration(
                    PROJECTS_DIR / ".meshes", mesh_id, length=plate.length_mm, width=plate.width_mm,
                    size=user_spec.get("mesh", {}).get("size_mm"),
                )
            bindings = verify_written_plate(
                keyword, mesh, material=(plate.density_g_per_mm3, plate.youngs_mpa, plate.poisson),
                thickness=plate.thickness_mm,
            )
            binding_check = {"mesh_binding_check": {"ok": True, "mesh_id": mesh_id, "bindings": bindings}}
        except (IndexError, KeyError, TypeError, ValueError, OSError) as exc:
            errors.append(f"网格绑定检查失败：{exc}")
            binding_check = {"mesh_binding_check": {"ok": False, "mesh_id": mesh_id}}

    from .project_store import project_validation_fingerprint

    return {
        "validation_fingerprint": project_validation_fingerprint(path),
        "ok": not errors,
        "errors": errors,
        "warnings": warnings,
        "readiness": {"ok_for_gui_preview": not errors, "ok_for_solver_draft": False,
                      "ok_for_production_review": False},
        "keyword_path": str(keyword_path),
        "spec_path": str(spec_path),
        **binding_check,
    }


def extract_physical_values(user_spec: JSONDict) -> JSONDict:
    if "geometry" in user_spec or "material" in user_spec or "mesh" in user_spec:
        geometry = user_spec.get("geometry") or {}
        material = user_spec.get("material") or {}
        mesh = user_spec.get("mesh") or {}
        return {
            "length_mm": geometry.get("length_mm", 0),
            "width_mm": geometry.get("width_mm", 0),
            "thickness_mm": geometry.get("thickness_mm", 0),
            "mesh_size_mm": mesh.get("size_mm", 0),
            "density_g_per_mm3": material.get("density_g_per_mm3", 0),
            "youngs_mpa": material.get("youngs_mpa", 0),
        }
    return user_spec


def tool_build_mesh(args: JSONDict) -> JSONDict:
    return build_mesh(args, PROJECTS_DIR / ".meshes")


def rebuild_keyword(model_spec: JSONDict, mesh_id: str) -> tuple[str, JSONDict]:
    spec = make_plate_spec_from_model_spec(model_spec)
    mesh, grid = load_for_configuration(
        PROJECTS_DIR / ".meshes", mesh_id, length=spec.length_mm, width=spec.width_mm,
        size=model_spec.get("mesh", {}).get("size_mm"),
    )
    keyword, metadata = build_plate_keyword(spec, mesh=mesh, grid=grid)
    metadata.update(compiler=COMPILER, mesh_id=mesh_id, mesh_quality=mesh.quality,
                    model_type="shell_plate", element_family="shell")
    return keyword, metadata


def tool_configure_model(args: JSONDict) -> JSONDict:
    from .project_store import write_compiled_keyword_project

    if set(args) - {"spec", "mesh_id", "if_exists"} or args.get("if_exists", "error") != "error":
        raise ValueError("配置工具仅支持写到一个新项目。")
    model_spec = args.get("spec")
    allowed = {"project_name", "model_type", "unit_system", "geometry", "mesh", "material", "boundary_conditions"}
    if not isinstance(model_spec, dict) or model_spec.keys() - allowed:
        raise ValueError("配置字段不受支持。")
    if model_spec.get("model_type") != "shell_plate" or model_spec.get("unit_system") != UNITS:
        raise ValueError("配置工具仅支持当前 R12 矩形弹性壳板及指定单位制。")
    if model_spec.get("boundary_conditions") != [{"type": "fixed_edge", "edge": "x_min"}]:
        raise ValueError("当前配置实验要求固定 x_min 边缘。")
    geometry = model_spec.get("geometry")
    material = model_spec.get("material")
    sizing = model_spec.get("mesh", {})
    dimensions = {"length_mm", "width_mm", "thickness_mm"}
    constants = {"density_g_per_mm3", "youngs_mpa", "poisson"}
    if (not isinstance(geometry, dict) or geometry.keys() != dimensions
            or not isinstance(material, dict) or not constants <= material.keys()
            or material.keys() - (constants | {"name", "type"}) or material.get("type") != "elastic"
            or not isinstance(sizing, dict) or sizing.keys() - {"size_mm"}):
        raise ValueError("请提供完整几何、线弹性材料及受支持的网格字段。")
    physical = [*geometry.values(), *(material[key] for key in constants), *sizing.values()]
    if any(type(value) not in (int, float) or not 0 < value <= sys.float_info.max for value in physical):
        raise ValueError("几何、材料及网格参数须为可表示的有限正数。")
    spec = make_plate_spec_from_model_spec(model_spec)
    if any(ord(char) < 32 for char in spec.project_name) or len(spec.project_name.splitlines()) != 1:
        raise ValueError("项目名称不能含控制字符。")
    mesh_id = args.get("mesh_id")
    name = safe_project_name(spec.project_name)
    if name != spec.project_name:
        raise ValueError("project_name contains unsupported characters")
    evidence = stage_evidence("input_writer")
    keyword, metadata = rebuild_keyword(model_spec, mesh_id)
    result = write_compiled_keyword_project(name, keyword, model_spec, metadata, require_valid=True)
    return {**result, **evidence, "mesh_id": mesh_id, "bindings": result["checks"]["mesh_binding_check"]["bindings"]}

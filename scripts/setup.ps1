param(
    [string]$LsppExe = "",
    [string]$OutputDir = "",
    [switch]$NonInteractive,
    [switch]$SkipDoctor,
    [switch]$SkipLsppValidation
)

$ErrorActionPreference = "Stop"
$Root = Resolve-Path (Join-Path $PSScriptRoot "..")
. (Join-Path $PSScriptRoot 'python_runtime.ps1')
$ProjectPython = Resolve-ProjectPython -Root $Root.Path

if ([string]::IsNullOrWhiteSpace($LsppExe)) {
    if ($NonInteractive) {
        throw "LsppExe is required in non-interactive mode. Use -LsppExe '<LS_PREPOST_EXE>'."
    }
    $LsppExe = Read-Host "Enter full path to lsprepost*.exe"
}

if ([string]::IsNullOrWhiteSpace($OutputDir)) {
    $OutputDir = Join-Path $Root "var\generated_configs"
}

if (-not $SkipLsppValidation -and ($LsppExe -notlike "*<LS_PREPOST_EXE>*")) {
    powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot "doctor.ps1") -LsppExe $LsppExe -RequireLsPrePost | Out-Host
    if ($LASTEXITCODE -ne 0) {
        throw "doctor.ps1 failed; refusing to generate MCP configs for an invalid LS-PrePost executable."
    }
} elseif (-not $SkipDoctor) {
    powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot "doctor.ps1") | Out-Host
    if ($LASTEXITCODE -ne 0) {
        throw "doctor.ps1 failed; refusing to generate MCP configs."
    }
}

Push-Location $Root
try {
    $env:PYTHONDONTWRITEBYTECODE = "1"
    & $ProjectPython -B -X utf8 (Join-Path $Root "scripts\generate_mcp_configs.py") --lspp-exe $LsppExe --out $OutputDir
    if ($LASTEXITCODE -ne 0) {
        throw "generate_mcp_configs.py failed with exit code $LASTEXITCODE"
    }
} finally {
    Pop-Location
}

$resolvedOutput = Resolve-Path $OutputDir
$envFile = Join-Path $resolvedOutput "lsprepost_mcp.local.env.ps1"
$escaped = $LsppExe.Replace("'", "''")
@(
    "# Local environment for lsprepost-mcp. This file is generated by scripts/setup.ps1.",
    "`$env:LSPP_EXE = '$escaped'",
    "`$env:PYTHONDONTWRITEBYTECODE = '1'"
) | Set-Content -LiteralPath $envFile -Encoding UTF8

Write-Output "Generated MCP configs in: $resolvedOutput"
Write-Output "Generated local env file: $envFile"
Write-Output "Use scripts\doctor.ps1 -LsppExe `"$LsppExe`" -RequireLsPrePost to re-check this machine."
